"""Calibration of the Heston model to an implied volatility surface.

The Fourier pricer in ``heston.py`` is fitted to a grid of market implied vols by bounded
non-linear least squares. Residuals are vega-weighted price errors,

    r_i = (C_model(K_i, T_i) - C_mkt(K_i, T_i)) / vega_mkt(K_i, T_i),

which to first order equal implied-vol errors, so the objective is a vol-point RMSE without
inverting Black-Scholes inside the optimiser. Fit quality is always reported in true implied-vol
points. Parameter identifiability is read from the Jacobian at the optimum.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from scipy.optimize import least_squares
from scipy.stats import norm

from heston import HestonParams, call_price, implied_vol

PARAM_NAMES = ("v0", "kappa", "theta", "xi", "rho")
LOWER = np.array([1e-4, 0.05, 1e-4, 0.05, -0.99])
UPPER = np.array([1.0, 10.0, 1.0, 2.0, 0.99])


@dataclass(frozen=True)
class Surface:
    """Implied vols on a (maturity, strike) grid; one entry per quote."""

    S: float
    r: float
    q: float
    T: np.ndarray
    K: np.ndarray
    iv: np.ndarray

    def __post_init__(self) -> None:
        if not (self.T.shape == self.K.shape == self.iv.shape and self.T.ndim == 1):
            raise ValueError("T, K and iv must be 1-D arrays of equal length")
        if np.any(self.T <= 0) or np.any(self.K <= 0) or np.any(self.iv <= 0):
            raise ValueError("T, K and iv must be positive")

    def __len__(self) -> int:
        return len(self.iv)

    @property
    def vega(self) -> np.ndarray:
        """Black-Scholes vega of each quote at its own market vol."""
        sq = np.sqrt(self.T)
        d1 = (np.log(self.S / self.K) + (self.r - self.q + 0.5 * self.iv**2) * self.T) / (self.iv * sq)
        return self.S * np.exp(-self.q * self.T) * norm.pdf(d1) * sq

    @property
    def prices(self) -> np.ndarray:
        from heston import bs_call

        return np.array(
            [bs_call(self.S, k, t, self.r, self.q, v) for k, t, v in zip(self.K, self.T, self.iv)]
        )


def synthetic_surface(
    p: HestonParams,
    S: float = 100.0,
    r: float = 0.03,
    q: float = 0.01,
    maturities=(0.25, 0.5, 1.0, 2.0),
    moneyness=(0.8, 0.9, 0.95, 1.0, 1.05, 1.1, 1.2),
    noise: float = 0.0,
    seed: int | None = None,
) -> Surface:
    """Implied vols generated by the Heston model, optionally with Gaussian vol noise.

    Strikes are set as multiples of each maturity's forward, so every expiry has the same
    log-moneyness grid.
    """
    rng = np.random.default_rng(seed)
    T, K, iv = [], [], []
    for t in maturities:
        fwd = S * np.exp((r - q) * t)
        for m in moneyness:
            k = m * fwd
            T.append(t)
            K.append(k)
            iv.append(implied_vol(call_price(S, k, t, r, q, p), S, k, t, r, q))
    iv_arr = np.array(iv) + noise * rng.standard_normal(len(iv))
    return Surface(S, r, q, np.array(T), np.array(K), iv_arr)


def model_ivs(x: np.ndarray, surf: Surface) -> np.ndarray:
    """Heston implied vols at the surface's quotes for parameter vector ``x``."""
    p = HestonParams(*x)
    return np.array(
        [
            implied_vol(call_price(surf.S, k, t, surf.r, surf.q, p), surf.S, k, t, surf.r, surf.q)
            for k, t in zip(surf.K, surf.T)
        ]
    )


def _residuals(x: np.ndarray, surf: Surface, mkt_prices: np.ndarray, vega: np.ndarray) -> np.ndarray:
    p = HestonParams(*x)
    model = np.array([call_price(surf.S, k, t, surf.r, surf.q, p) for k, t in zip(surf.K, surf.T)])
    return (model - mkt_prices) / vega


@dataclass
class CalibrationResult:
    params: HestonParams
    rmse_vol_pts: float  # root-mean-square implied-vol error, in vol points (1 = 1%)
    max_abs_vol_pts: float
    jacobian: np.ndarray  # d residual / d (v0, kappa, theta, xi, rho) at the optimum
    n_starts: int
    n_converged: int

    @property
    def vector(self) -> np.ndarray:
        p = self.params
        return np.array([p.v0, p.kappa, p.theta, p.xi, p.rho])

    def parameter_correlation(self) -> np.ndarray:
        """Correlation of parameter estimates, from the Gauss-Newton covariance (J'J)^-1."""
        return correlation_from_jacobian(self.jacobian)

    def condition_number(self) -> float:
        return float(np.linalg.cond(self.jacobian))


def correlation_from_jacobian(J: np.ndarray) -> np.ndarray:
    cov = np.linalg.pinv(J.T @ J)
    sd = np.sqrt(np.diag(cov))
    return cov / np.outer(sd, sd)


def calibrate(
    surf: Surface,
    n_starts: int = 6,
    seed: int = 0,
    fixed: dict[str, float] | None = None,
) -> CalibrationResult:
    """Fit Heston parameters to ``surf`` by multi-start bounded least squares.

    Starting points are drawn uniformly inside the bounds (restricted to a plausible equity
    region) with a fixed seed, plus one deterministic "typical equity" start. ``fixed`` pins
    named parameters, which is how profile fits over kappa are done.
    """
    fixed = dict(fixed or {})
    unknown = set(fixed) - set(PARAM_NAMES)
    if unknown:
        raise ValueError(f"unknown parameters: {sorted(unknown)}")
    free = np.array([n not in fixed for n in PARAM_NAMES])
    base = np.array([fixed.get(n, np.nan) for n in PARAM_NAMES])
    mkt, vega = surf.prices, surf.vega

    def full(z: np.ndarray) -> np.ndarray:
        x = base.copy()
        x[free] = z
        return x

    rng = np.random.default_rng(seed)
    lo, hi = np.array([0.01, 0.3, 0.01, 0.1, -0.95]), np.array([0.15, 6.0, 0.15, 1.2, -0.1])
    starts = [np.array([0.04, 2.0, 0.04, 0.5, -0.5])]
    starts += [lo + (hi - lo) * rng.random(5) for _ in range(n_starts - 1)]

    best, n_ok = None, 0
    for s in starts:
        try:
            sol = least_squares(
                lambda z: _residuals(full(z), surf, mkt, vega),
                s[free],
                bounds=(LOWER[free], UPPER[free]),
                x_scale=(UPPER - LOWER)[free] / 10,
                xtol=1e-10,
                ftol=1e-10,
                max_nfev=200,
            )
        except (ValueError, FloatingPointError):
            continue
        n_ok += 1
        if best is None or sol.cost < best.cost:
            best = sol
    if best is None:
        raise RuntimeError("no starting point converged")

    x = full(best.x)
    err = (model_ivs(x, surf) - surf.iv) * 100
    jac = np.zeros((len(surf), 5))
    jac[:, free] = best.jac
    return CalibrationResult(
        params=HestonParams(*map(float, x)),
        rmse_vol_pts=float(np.sqrt(np.mean(err**2))),
        max_abs_vol_pts=float(np.max(np.abs(err))),
        jacobian=jac,
        n_starts=len(starts),
        n_converged=n_ok,
    )


def kappa_profile(surf: Surface, kappas, seed: int = 0, n_starts: int = 3) -> list[CalibrationResult]:
    """Refit the other four parameters with kappa pinned to each value in ``kappas``.

    A flat RMSE profile means kappa is poorly identified by the surface.
    """
    return [calibrate(surf, n_starts=n_starts, seed=seed, fixed={"kappa": k}) for k in kappas]
